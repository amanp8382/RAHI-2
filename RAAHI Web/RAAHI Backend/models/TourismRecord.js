const mongoose = require('mongoose');
const schema = new mongoose.Schema({
  state: { type: String, required: true, index: true },
  kind: { type: String, enum: ['destinations', 'advisories', 'complaints', 'cases', 'services'], required: true },
  title: { type: String, required: true, maxlength: 160 },
  description: { type: String, maxlength: 4000, default: '' },
  city: { type: String, maxlength: 120, default: '' },
  district: { type: String, maxlength: 120, default: '' },
  status: { type: String, required: true },
  category: { type: String, maxlength: 80, default: '' },
  openingHours: { type: String, maxlength: 200 },
  entryFee: { type: Number, min: 0 },
  facilities: { type: String, maxlength: 1200 },
  accessibility: { type: String, maxlength: 1200 },
  lat: { type: Number, min: -90, max: 90 },
  lng: { type: Number, min: -180, max: 180 },
  dailyCapacity: { type: Number, min: 1 },
  severity: { type: String, enum: ['information', 'watch', 'urgent'] },
  source: { type: String, maxlength: 500 },
  sourceUrl: { type: String, maxlength: 1000 },
  verified: { type: Boolean, default: false },
  expiresAt: Date,
  publishedAt: Date,
  rating: { type: Number, min: 1, max: 5 },
  channel: { type: String, maxlength: 100 },
  assignee: { type: String, maxlength: 160 },
  resolution: { type: String, maxlength: 2000 },
  caseType: { type: String, enum: ['police', 'medical', 'travel assistance'] },
  reference: { type: String, maxlength: 120 },
  referredTo: { type: String, maxlength: 160 },
  firstResponseAt: Date,
  resolvedAt: Date,
  serviceType: { type: String, enum: ['guide', 'hotel', 'transport', 'help centre'] },
  phone: { type: String, maxlength: 40 },
  address: { type: String, maxlength: 1000 },
  website: { type: String, maxlength: 1000 },
  createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true }
}, { timestamps: true });
schema.index({ state: 1, kind: 1, updatedAt: -1 });
module.exports = mongoose.model('TourismRecord', schema);
